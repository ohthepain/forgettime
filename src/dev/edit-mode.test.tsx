// @vitest-environment jsdom
import { act, fireEvent, within } from '@testing-library/react'
import { expect, it, vi } from 'vite-plus/test'

it('keeps product controls intact, flags lost targets and exports only the selected revision', async () => {
  vi.useFakeTimers()
  vi.stubGlobal('CSS', { escape: (value: string) => value })
  vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockReturnValue({ left: 50, top: 50, right: 150, bottom: 80, width: 100, height: 30, x: 50, y: 50, toJSON() {} })
  sessionStorage.setItem('forgettime:visual-feedback:v1', JSON.stringify({ enabled: true, requests: [], revision: 0 }))
  const product = document.createElement('button')
  product.id = 'product-action'; product.textContent = 'Product action'
  const action = vi.fn(); product.onclick = action; document.body.append(product)
  await act(async () => { await import('./edit-mode') })
  const host = document.getElementById('dev-edit-mode')!
  const ui = within(host.shadowRoot! as unknown as HTMLElement)
  fireEvent.pointerMove(product)
  await act(async () => { vi.advanceTimersByTime(250) })
  fireEvent.click(ui.getByRole('button', { name: 'Mark element for deletion' }))
  expect(product.isConnected).toBe(true)
  expect(product.getAttribute('style')).toBeNull()
  fireEvent.click(product); expect(action).toHaveBeenCalledOnce()
  expect(ui.getByText('Marked for deletion')).toBeTruthy()
  fireEvent.click(ui.getByRole('button', { name: 'Undo' }))
  fireEvent.click(ui.getByRole('button', { name: 'Enter requested dimensions' }))
  fireEvent.change(ui.getByRole('spinbutton', { name: 'Width' }), { target: { value: '200' } })
  fireEvent.click(ui.getByRole('button', { name: 'Save request' }))
  expect(product.getAttribute('style')).toBeNull()
  fireEvent.click(ui.getByRole('button', { name: '💬 General comment' }))
  fireEvent.change(ui.getByRole('textbox', { name: 'Feedback' }), { target: { value: 'Do not include this comment' } })
  fireEvent.click(ui.getByRole('button', { name: 'Save request' }))
  fireEvent.click(ui.getByRole('button', { name: 'Review changes (2)' }))
  fireEvent.click(ui.getByRole('checkbox', { name: 'comment: Do not include this comment' }))
  product.remove()
  await act(async () => { vi.advanceTimersByTime(100) })
  expect(ui.getByText('Target missing or changed — needs review')).toBeTruthy()
  fireEvent.click(ui.getByRole('button', { name: 'Prepare selected report' }))
  const report = JSON.parse((ui.getByRole('textbox', { name: 'Selected feedback report' }) as HTMLTextAreaElement).value)
  expect(report.requests).toHaveLength(1)
  expect(report.requests[0].requested).toEqual({ width: 200, height: 30 })
  expect(report.requests[0].target.selector).toBe('#product-action')
  expect(report.selectedIds).toEqual([report.requests[0].id])
  fireEvent.click(ui.getByRole('checkbox', { name: 'comment: Do not include this comment' }))
  expect(ui.queryByRole('textbox', { name: 'Selected feedback report' })).toBeNull()
  const saved = JSON.parse(sessionStorage.getItem('forgettime:visual-feedback:v1')!)
  expect(saved.submitted).toBeUndefined()
  expect(saved.requests.every((r: { selected: boolean }) => r.selected)).toBe(true)
  vi.clearAllTimers(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals()
})
